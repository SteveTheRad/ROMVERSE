"""Authoritative pre-v1 compatibility inventory for retained durable records.

This module is deliberately dependency-neutral.  It describes storage and wire
compatibility; importing it performs no migration, persistence, or authority
decision.  Application loaders remain the source of enforcement, while the
inventory tests bind every declaration back to its implementation and existing
compatibility regression.
"""

from __future__ import annotations

from dataclasses import dataclass
from enum import StrEnum


class DurableSchemaDomain(StrEnum):
    PROJECT = "project"
    EVIDENCE = "evidence"
    HISTORY = "history"
    GUARDIAN = "guardian"
    RECOVERY = "recovery"
    KNOWLEDGE = "knowledge"
    UPDATE = "update"
    DESKTOP_COMPANION_LINK = "desktop-companion-link"


@dataclass(frozen=True, slots=True)
class DurableSchemaSpec:
    """One retained format and its complete pre-v1 compatibility posture."""

    format_id: str
    domain: DurableSchemaDomain
    current_version: int
    supported_read_versions: tuple[int, ...]
    migration_or_rederivation: str
    audit_only: bool
    failure_behavior: str
    authority_effect: str
    implementation_file: str
    implementation_marker: str
    compatibility_tests: tuple[str, ...]
    legacy_unversioned_read: bool = False


STRICT = (
    "No implicit migration. Accept only the declared versions after strict shape, size, path, "
    "identity, and integrity validation."
)
UPGRADE_ON_VERIFIED_SAVE = (
    "Read the declared legacy versions, but emit the current version only after current evidence "
    "has been independently revalidated; never upgrade merely because parsing succeeded."
)
REDERIVE = (
    "Treat saved content as a cache/evidence candidate and deterministically re-derive its current "
    "bindings before use; stale content is replaced only by a normal verified save."
)
AUDIT_PRESERVE = (
    "Never rewrite historical meaning. Preserve valid older evidence as audit history and append a "
    "new current record when a later event occurs."
)
SAFE_DEFAULT = (
    "Normalize supported preferences into the current version on the next explicit save; invalid "
    "or future data falls back to safe defaults and cannot create authority."
)
WIRE_ONLY = (
    "Do not migrate received bytes. Parse the declared wire versions into a bounded neutral model; "
    "future, malformed, or duplicate-field payloads are rejected."
)

FAIL_CLOSED = (
    "Reject the record and withhold every dependent Guardian, Recovery, build, install, or device "
    "authority until fresh valid evidence is produced."
)
UNAVAILABLE = (
    "Treat the record as unavailable/stale, show no verified claim from it, and require fresh "
    "derivation before any dependent consequential gate may pass."
)
PRESERVE_AND_SKIP = (
    "Do not infer success from unreadable history. Preserve the source where the owner supports it, "
    "exclude the bad entry from trusted views, and append no replacement claim automatically."
)
DEFAULTS_ONLY = (
    "Ignore the invalid preference/state record, use conservative defaults, and grant no authority."
)

AUTHORITY_NONE = (
    "None; metadata, preferences, exports, and wire data never grant execution authority."
)
AUTHORITY_EVIDENCE = (
    "Evidence only; a valid record may satisfy its named evidence input but is never build, flash, "
    "install, device, consent, or execution authority by itself."
)
AUTHORITY_GUARDIAN = (
    "Guardian input only; it contributes solely to the exact validated chain and is never standalone "
    "execution authority."
)
AUTHORITY_AUDIT = "Audit only; it records what was observed and grants no present authority."


def _spec(
    format_id: str,
    domain: DurableSchemaDomain,
    current: int,
    reads: tuple[int, ...],
    implementation: str,
    marker: str,
    tests: str,
    *,
    policy: str,
    failure: str,
    authority: str,
    audit_only: bool = False,
    legacy_unversioned: bool = False,
) -> DurableSchemaSpec:
    return DurableSchemaSpec(
        format_id=format_id,
        domain=domain,
        current_version=current,
        supported_read_versions=reads,
        migration_or_rederivation=policy,
        audit_only=audit_only,
        failure_behavior=failure,
        authority_effect=authority,
        implementation_file=implementation,
        implementation_marker=marker,
        compatibility_tests=(tests,),
        legacy_unversioned_read=legacy_unversioned,
    )


