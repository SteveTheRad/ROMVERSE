def schema_by_format(format_id: str) -> DurableSchemaSpec | None:
    """Return one declaration without importing a storage owner."""

    return next((item for item in DURABLE_SCHEMA_INVENTORY if item.format_id == format_id), None)


def schemas_for_domain(domain: DurableSchemaDomain) -> tuple[DurableSchemaSpec, ...]:
    """Return the stable, format-sorted inventory for one named retention domain."""

    return tuple(
        sorted(
            (item for item in DURABLE_SCHEMA_INVENTORY if item.domain is domain),
            key=lambda item: item.format_id,
        )
    )
