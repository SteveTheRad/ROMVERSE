from __future__ import annotations

import json

from romverse.device_packs.models import DevicePack
from romverse.device_packs.registry import DevicePackRegistry
from romverse.device_packs.source_audit import summarize_sources


def render_companion_kotlin(registry: DevicePackRegistry) -> str:
    """Render read-only OEM knowledge for Companion from the verified Desktop registry."""

    packs = tuple(
        sorted(
            (
                pack
                for pack in registry.packs
                if pack.knowledge_sources and pack.manufacturers != ("*",)
            ),
            key=lambda item: (-item.priority, item.pack_id),
        )
    )
    generic = next(
        (
            pack
            for pack in registry.packs
            if pack.pack_id == "android.generic" and pack.knowledge_sources
        ),
        None,
    )
    if generic is None:
        raise ValueError("Companion Atlas requires a sourced android.generic fallback Pack")
    if not packs:
        raise ValueError("Companion Atlas requires at least one sourced OEM Pack")
    exact_identities = tuple(
        sorted(
            (
                pack
                for pack in registry.packs
                if pack.manufacturers != ("*",)
                and pack.model_patterns
                and pack.product_patterns
                and (
                    pack.build_contract is not None
                    or (
                        len(pack.model_patterns) == 1
                        and len(pack.product_patterns) == 1
                        and not _has_glob(pack.model_patterns[0])
                        and not _has_glob(pack.product_patterns[0])
                    )
                )
            ),
            key=lambda item: (-item.priority, item.pack_id),
        )
    )
    summary = summarize_sources(registry)

    lines = [
        "// Generated by scripts/sync_companion_device_atlas.py. Do not edit by hand.",
        "package com.radforge.romverse.companion",
        "",
        "internal object GeneratedDeviceAtlasPacks {",
        f"    const val catalogPackCount: Int = {len(packs) + 1}",
        f"    const val catalogSourceCount: Int = {summary.source_reference_count}",
        f"    const val catalogReviewDueCount: Int = {summary.review_due_count}",
        f"    const val exactIdentityCount: Int = {len(exact_identities)}",
        "",
        "    val exactIdentities: List<CompanionExactIdentity> = listOf(",
    ]
    for pack in exact_identities:
        lines.extend(_identity_lines(pack, 8))
    lines.extend(
        [
            "    )",
            "",
            "    val oemPacks: List<CompanionDevicePack> = listOf(",
        ]
    )
    for pack in packs:
        lines.extend(_pack_lines(pack, 8))
    lines.extend(
        [
            "    )",
            "",
            "    val generic: CompanionDevicePack = CompanionDevicePack(",
            *_pack_arguments(generic, 8),
            "    )",
            "}",
            "",
        ]
    )
    return "\n".join(lines)


def _identity_lines(pack: DevicePack, spaces: int) -> list[str]:
    indent = " " * spaces
    manufacturers = ", ".join(_quote(value) for value in pack.manufacturers)
    marketing_name = pack.display_name.split(" /", maxsplit=1)[0].strip()
    return [
        f"{indent}CompanionExactIdentity(",
        f"{indent}    packId = {_quote(pack.pack_id)},",
        f"{indent}    packSha256 = {_quote(pack.sha256)},",
        f"{indent}    priority = {pack.priority},",
        f"{indent}    marketingName = {_quote(marketing_name)},",
        f"{indent}    manufacturers = setOf({manufacturers}),",
        f"{indent}    modelPatterns = {_string_set(pack.model_patterns)},",
        f"{indent}    productPatterns = {_string_set(pack.product_patterns)},",
        f"{indent}),",
    ]


def _pack_lines(pack: DevicePack, spaces: int) -> list[str]:
    indent = " " * spaces
    return [
        f"{indent}CompanionDevicePack(",
        *_pack_arguments(pack, spaces + 4),
        f"{indent}),",
    ]


def _pack_arguments(pack: DevicePack, spaces: int) -> list[str]:
    indent = " " * spaces
    manufacturers = ", ".join(_quote(value) for value in pack.manufacturers)
    boundary = " ".join(pack.notes) or (
        "Read-only source context only; exact model and firmware evidence remains required."
    )
    lines = [
        f"{indent}packId = {_quote(pack.pack_id)},",
        f"{indent}version = {_quote(pack.version)},",
        f"{indent}packSha256 = {_quote(pack.sha256)},",
        f"{indent}priority = {pack.priority},",
        f"{indent}displayName = {_quote(pack.display_name)},",
        f"{indent}manufacturers = setOf({manufacturers}),",
        f"{indent}modelPatterns = {_string_set(pack.model_patterns)},",
        f"{indent}productPatterns = {_string_set(pack.product_patterns)},",
        f"{indent}sources = listOf(",
    ]
    for source in pack.knowledge_sources:
        lines.extend(
            [
                f"{indent}    AtlasSource(",
                f"{indent}        sourceId = {_quote(source.source_id)},",
                f"{indent}        label = {_quote(source.label)},",
                f"{indent}        authority = {_quote(source.authority)},",
                f"{indent}        scope = {_quote(source.scope)},",
                f"{indent}        verifiedOn = {_quote(source.verified_on)},",
                f"{indent}        url = {_quote(source.url)},",
                f"{indent}    ),",
            ]
        )
    lines.extend(
        [
            f"{indent}),",
            f"{indent}boundary = {_quote(boundary)},",
        ]
    )
    return lines


def _quote(value: str) -> str:
    return json.dumps(value, ensure_ascii=True)


def _string_set(values: tuple[str, ...]) -> str:
    return "setOf(" + ", ".join(_quote(value) for value in values) + ")"


def _has_glob(value: str) -> bool:
    return any(marker in value for marker in "*?[]")
