SUPER_SIZE = 262144
SUPER_MAGIC = b"SIMULATED SUPER - NOT ANDROID\n"


def _sha(data):
    return hashlib.sha256(data).hexdigest()


@pytest.fixture(scope="module")
def signing_key():
    return rsa.generate_private_key(public_exponent=65537, key_size=2048)


def _super_container(images):
    inventory = json.dumps([(name, len(data)) for name, data in images.items()]).encode()
    data = SUPER_MAGIC + struct.pack("!I", len(inventory)) + inventory + b"".join(images.values())
    assert len(data) <= SUPER_SIZE
    return data.ljust(SUPER_SIZE, b"\0")


def _unpack_container(data):
    assert data.startswith(SUPER_MAGIC) and len(data) == SUPER_SIZE
    position = len(SUPER_MAGIC)
    length = struct.unpack("!I", data[position : position + 4])[0]
    position += 4
    inventory = json.loads(data[position : position + length])
    position += length
    images = {}
    for name, size in inventory:
        assert name not in images and name in {"product_a", "system_a", "system_ext_a"}
        images[name] = data[position : position + size]
        assert len(images[name]) == size
        position += size
    assert not any(data[position:])
    return images


class InertBuildTools:
    """Simulated tool transport; AVB production parsers verify its actual bytes."""

    def __init__(self, raw, descriptors, *, fault=""):
        self.raw = raw
        self.descriptors = descriptors
        self.fault = fault
        self.calls = []

    def run(self, args, timeout=10, cwd=None):
        command = tuple(str(arg) for arg in args)
        self.calls.append(command)
        executable = next(
            (
                name
                for name in (
                    "fakeroot",
                    "fsck.erofs",
                    "avbtool",
                    "lpmake",
                    "simg2img",
                    "lpunpack",
                    "lpdumps",
                )
                if name in command[0]
            ),
            None,
        )
        assert executable is not None, f"No real or unexpected tool may run: {command}"
        output = "SIMULATED BUILD TOOL OUTPUT\n"
        if executable == "fakeroot":
            Path(command[-2]).write_bytes(self.raw["candidate_product"][:8192])
        elif executable == "fsck.erofs":
            assert Path(command[-1]).read_bytes() == self.raw["candidate_product"][:8192]
        elif executable == "avbtool" and command[1] == "add_hashtree_footer":
            path = Path(command[command.index("--image") + 1])
            assert path.read_bytes() == self.raw["candidate_product"][:8192]
            assert int(command[command.index("--partition_size") + 1]) == len(
                self.raw["candidate_product"]
            )
            assert command[command.index("--salt") + 1] == b"salt".hex()
            assert command[command.index("--hash_algorithm") + 1] == "sha256"
            path.write_bytes(self.raw["candidate_product"])
        elif executable == "avbtool" and command[1] == "make_vbmeta_image":
            inputs = [
                Path(command[index + 1])
                for index, arg in enumerate(command)
                if arg == "--include_descriptors_from_image"
            ]
            assert [path.name for path in inputs] == ["product.img", "system.img", "system_ext.img"]
            assert [path.read_bytes() for path in inputs] == [
                self.raw[name] for name in ("candidate_product", "system", "system_ext")
            ]
            descriptors = list(self.descriptors)
            if self.fault == "child-descriptor":
                _, descriptors[0] = _partition("product", b"Z")
            Path(command[command.index("--output") + 1]).write_bytes(_meta(descriptors))
        elif executable == "avbtool" and command[1] == "info_image":
            assert command[2] == "--image" and Path(command[3]).name == "vbmeta_system.img"
            output = "Algorithm: NONE\n"
        elif executable == "lpmake":
            images = {}
            for index, arg in enumerate(command):
                if arg == "--image":
                    name, path = command[index + 1].split("=", 1)
                    images[name] = Path(path).read_bytes()
            assert set(images) == {"product_a", "system_a", "system_ext_a"}
            Path(command[command.index("--output") + 1]).write_bytes(_super_container(images))
        elif executable == "simg2img":
            Path(command[2]).write_bytes(Path(command[1]).read_bytes())
        elif executable == "lpunpack":
            for name, data in _unpack_container(Path(command[1]).read_bytes()).items():
                (Path(command[2]) / f"{name}.img").write_bytes(data)
        elif executable == "lpdumps":
            output = json.dumps(
                {
                    name: len(data)
                    for name, data in _unpack_container(Path(command[1]).read_bytes()).items()
                }
            )
        else:
            pytest.fail(f"Unexpected simulated tool operation: {command}")
        return CommandResult(command, 0, output, "")


def _fixture(tmp_path, key, *, fault=""):
    template_root = tmp_path / "template"
    template_root.mkdir()
    template, template_project, template_registry, _, _, _ = build_fixture(template_root)
    raw, desc = {}, {}
    for name, byte in (("product", b"P"), ("system", b"S"), ("system_ext", b"E")):
        raw[name], desc[name] = _partition(name, byte, key=key)
    raw["candidate_product"], product_desc = _partition(
        "product", b"N", digest=b"x" * 32 if fault == "merkle-root" else None
    )
    raw["root"] = _meta((_chain("vbmeta_system", key),), key)
    if fault == "source-signature":
        corrupt = bytearray(raw["root"])
        corrupt[256 + 32] ^= 1
        raw["root"] = bytes(corrupt)
    raw["source_child"] = _meta(tuple(desc.values()), key)
    images = _files()
    images["images/super.img"] = b"ORIGINAL SIMULATED SUPER".ljust(SUPER_SIZE, b"\0")
    images["images/vbmeta.img"] = raw["root"]
    images["images/vbmeta_system.img"] = raw["source_child"]
    manifest = _integer(12, 0) + b"".join(
        payload_partition(name, images[f"images/{name}.img"]) for name in REQUIRED_PARTITIONS
    )
    manifest += b"".join(
        payload_partition(name, raw[name]) for name in ("product", "system", "system_ext")
    )
    manifest += payload_partition("vbmeta_system", raw["source_child"])
    context_root = tmp_path / "candidate"
    context_root.mkdir()
    context = base_fixture(context_root, image_contents=images, manifest=manifest)
    store, project = context.store, context.project
    working = store.working_root / project.project_id
    shutil.copytree(template.working_root / template_project.project_id, working)
    (working / "tree" / "payload.bin").write_bytes(context.payload)
    source_root = working / "tree" / "partition_files" / "product" / "root"
    source_root.mkdir(parents=True)
    (source_root / "SIMULATION-ONLY.txt").write_text(
        "The candidate deliberately differs from source"
    )
    for name in ("product", "system", "system_ext"):
        (working / "partitions" / f"{name}.img").write_bytes(raw[name])
    metadata_root = store.projects_root / project.project_id / "rebuild-metadata"
    shutil.copytree(
        template.projects_root / template_project.project_id / "rebuild-metadata", metadata_root
    )
    metadata_path = metadata_root / "product.romverse"
    data = json.loads(metadata_path.read_text())
    data["source_sha256"] = _sha(raw["product"])
    metadata_path.write_text(json.dumps(data))
    records = [
        {
            "name": name,
            "extracted_path": (working / "partitions" / f"{name}.img")
            .relative_to(store.workspace)
            .as_posix(),
            "actual_bytes": len(raw[name]),
            "sha256": _sha(raw[name]),
        }
        for name in ("product", "system", "system_ext")
    ]
    (store.projects_root / project.project_id / "payload-manifest.romverse").write_text(
        json.dumps(
            {
                "format": "romverse.payload-manifest",
                "schema_version": 1,
                "project_id": project.project_id,
                "source_original_sha256": project.original.sha256,
                "payload_sha256": _sha(context.payload),
                "partitions": records,
            }
        )
    )
    template_pack = template_registry.packs[0]
    contract = template_pack.build_contract
    product_rule, system_rule = contract.partitions
    rules = (
        replace(
            product_rule,
            source_size_bytes=len(raw["product"]),
            size_bytes=len(raw["candidate_product"]),
            source_sha256=_sha(raw["product"]),
            avb_hashtree=AvbHashtreeParameters("sha256", b"salt".hex(), False),
        ),
        replace(
            system_rule,
            source_size_bytes=len(raw["system"]),
            size_bytes=len(raw["system"]),
            source_sha256=_sha(raw["system"]),
        ),
        replace(
            system_rule,
            name="system_ext",
            source_size_bytes=len(raw["system_ext"]),
            size_bytes=len(raw["system_ext"]),
            source_sha256=_sha(raw["system_ext"]),
        ),
    )
    contract = replace(
        contract,
        source=replace(
            contract.source,
            archive_sha256=project.original.sha256,
            payload_sha256=_sha(context.payload),
        ),
        super_size_bytes=SUPER_SIZE,
        groups=(
            DynamicPartitionGroup("group_a", SUPER_SIZE),
            DynamicPartitionGroup("group_b", SUPER_SIZE),
        ),
        partitions=rules,
        vbmeta_descriptor_partitions=("product", "system", "system_ext"),
        top_level_vbmeta_sha256=_sha(raw["root"]),
        vbmeta_system_sha256=_sha(raw["source_child"]),
    )
    context.registry = DevicePackRegistry(
        (
            replace(
                template_pack,
                pack_id=project.device_pack_id,
                manufacturers=("Xiaomi",),
                product_patterns=("popsicle",),
                build_contract=contract,
            ),
        )
    )
    context.tools = _executable_tools(tmp_path / "tools")
    context.runner = InertBuildTools(
        raw, (product_desc, desc["system"], desc["system_ext"]), fault=fault
    )
    RomBuildPlanner(store).plan(project.project_id)
    DeviceBuildContractService(store, context.registry, context.tools).create_plan(
        project.project_id
    )
    context.build = LocalDeviceBuildExecutor(
        store, context.registry, context.tools, context.runner
    ).execute(project.project_id)
    context.service = CandidateInstallationService(
        store, context.registry, context.tools, context.runner
    )
    context.raw = raw
    return context


def _prepare(context):
    return context.service.prepare(context.project.project_id, context.procedure.project_id)


def test_real_build_base_avb_and_candidate_boundaries_compose_two_plus_48(tmp_path, signing_key):
    context = _fixture(tmp_path, signing_key)
    recipe = _prepare(context)
    base = context.service.base.load(context.project.project_id)
    avb = context.service.avb.load(context.project.project_id)
    assert type(context.service.base) is BaseImageCompatibilityService
    assert type(context.service.avb) is CandidateAvbService
    assert len(recipe.images) == 50 and len(recipe.steps) == 53
    assert sum(origin.source_kind == "rebuilt" for origin in recipe.origins) == 2
    assert sum(origin.source_kind == "base-package" for origin in recipe.origins) == 48
    assert recipe.steps == context.recipe.steps
    assert recipe.base_receipt_digest == base.receipt_digest == avb.base_receipt_digest
    assert recipe.avb_receipt_digest == avb.receipt_digest
    assert recipe.build_receipt_digest == avb.build_receipt_digest == context.build.receipt_digest
    assert avb.root_algorithm == "SHA256_RSA2048" and avb.child_algorithm == "NONE"
    assert not avb.oem_trusted and not avb.candidate_signed and not avb.phone_changed
    assert not base.phone_changed and base.execution_authority == avb.execution_authority == "none"
    assert {row.partition for row in avb.descriptors} == {"product", "system", "system_ext"}
    candidates = {
        output.name: (context.store.workspace / output.path).read_bytes()
        for output in context.build.outputs
    }
    assert candidates["product.img"] != context.raw["product"]
    assert candidates["vbmeta_system.img"] != context.images["images/vbmeta_system.img"]
    assert candidates["super.img"] != context.images["images/super.img"]
    assert _unpack_container(candidates["super.img"]) == {
        "product_a": candidates["product.img"],
        "system_a": context.raw["system"],
        "system_ext_a": context.raw["system_ext"],
    }
    verification = context.store.workspace / context.build.outputs[0].path
    report = json.loads((verification.parent / "verification.romverse").read_text())
    assert len(report["partitions"]) == 3 and all(row["matches"] for row in report["partitions"])
    assert report["super_sha256"] == _sha(candidates["super.img"])
    records = [
        context.store.projects_root / context.project.project_id / service.RECEIPT_NAME
        for service in (context.service.base, context.service.avb)
    ]
    saved = [(path.read_bytes(), path.stat().st_mtime_ns) for path in records]
    assert context.service.verify(recipe) == recipe
    assert [(path.read_bytes(), path.stat().st_mtime_ns) for path in records] == saved
    assert any(command[1] == "info_image" for command in context.runner.calls)
    assert not any(
        "fastboot" in command[0] or "adb" in command[0] for command in context.runner.calls
    )


