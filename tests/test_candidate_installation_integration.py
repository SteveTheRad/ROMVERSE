class InertCandidatePhone(InstallationPhone):
    """Accept only exact prepared bytes; no physical transport exists."""

    def __init__(self, expected):
        super().__init__()
        self.expected = expected

    def run(self, args, timeout=10, cwd=None):
        command = tuple(map(str, args))
        operation = command[3:] if command[1:3] == ("-s", self.serial) else ()
        if operation[:2] == ("-S", "700M"):
            operation = operation[2:]
        if Path(command[0]).name == "fastboot" and operation[:1] == ("flash",):
            assert len(operation) == 3
            content = Path(operation[2]).read_bytes()
            assert content == self.expected[operation[1]]
            self.calls.append(command)
            self.changes.append(command[3:])
            self.written.append((operation[1], content))
            return CommandResult(command, 0, "", "SIMULATED ONLY: no phone")
        return super().run(args, timeout=timeout, cwd=cwd)


def test_real_candidate_runtime_writes_all_53_steps_with_exact_mixed_origins(tmp_path, signing_key):
    context = _fixture(tmp_path, signing_key)
    recipe = _prepare(context)
    origins = {origin.member: origin for origin in recipe.origins}
    expected = {}
    for step in recipe.steps:
        if step.action != "flash":
            continue
        origin = origins[step.image_member]
        expected[step.partition] = (
            (context.store.workspace / origin.relative_path).read_bytes()
            if origin.source_kind == "rebuilt"
            else context.images[f"images/{Path(step.image_member).name}"]
        )
    phone = InertCandidatePhone(expected)
    fastboot = next(Path(tool.path) for tool in context.tools if tool.name == "Fastboot")
    fastboot.chmod(0o700)
    flash = LocalFlashService(context.store.workspace, phone, fastboot)
    executor = SourceInstallationExecutor(context.service, flash)
    plan = executor.inspect(phone.device(), recipe)
    assert not phone.changes
    result = executor.execute(plan, accepted_digest=plan.plan_digest, risk_accepted=True)
    assert result.state is LocalFlashState.COMPLETED, result.summary
    assert _actual_changes(phone) == _expected_changes()
    assert len(phone.written) == 50 and len(result.results) == 53
    assert dict(phone.written) == expected
    assert not result.boot_verified
    document = json.loads(result.receipt_path.read_text())
    assert document["format"] == "romverse.candidate-installation"
    assert document["candidate_provenance"]["base_receipt_digest"] == recipe.base_receipt_digest
    assert document["candidate_provenance"]["avb_receipt_digest"] == recipe.avb_receipt_digest
    assert document["candidate_provenance"]["build_receipt_digest"] == context.build.receipt_digest
    assert not document["readback_verified"] and not document["production_certification"]
    assert flash.audit.verify().valid
